// Copies the VS Code-independent analysis engine from ../src into ./engine so the API
// builds as a self-contained project (Vercel root directory = server/). The copy is
// generated — edit the originals in ../src, never files under ./engine.
import { cpSync, rmSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', 'src');
const target = join(here, '..', 'engine');
const folders = ['core', 'analyzers', 'scoring', 'ai', 'models', 'utils'];

if (!existsSync(source)) {
  if (existsSync(target)) {
    console.log('sync-engine: ../src not found, using existing ./engine');
    process.exit(0);
  }
  console.error('sync-engine: ../src not found. On Vercel, enable "Include files outside the root directory".');
  process.exit(1);
}
rmSync(target, { recursive: true, force: true });
for (const folder of folders) {
  cpSync(join(source, folder), join(target, folder), { recursive: true });
}
writeFileSync(join(target, 'README.md'), 'Generated by scripts/sync-engine.mjs from ../src. Do not edit.\n');
console.log(`sync-engine: copied ${folders.join(', ')} from ../src`);
